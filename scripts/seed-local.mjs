async function create(api, title, description, tools, price, document) {
  const workspace = await api('workspace');
  const existing = workspace.assets.find(a => a.title === title);
  if (existing) return workspace.versions.find(v => v.assetId === existing.id && v.version === '1.0.0');
  const kind = document ? 'document' : 'skill';
  const content = document ?? JSON.stringify({ schemaVersion: 1, steps: tools.map(tool => ({ tool })) }, null, 2);
  const form = new FormData();
  form.set('metadata', JSON.stringify({ title, summary: description, kind, version: '1.0.0', license, limitations: ['플랫폼이 제작한 작동 확인용 예제입니다. 실제 업무 품질을 보장하지 않습니다.', document ? '문서 내용의 전문성·사실성과 AI 답변 개선 효과는 미평가입니다.' : 'market-tools/1.0.0 도구만 사용합니다. 규칙 밖의 사례는 탐지·처리하지 못합니다.'] }));
  form.set('file', new Blob([content], { type: 'application/octet-stream' }), document ? 'reference.md' : 'skill.json');
  const { version } = await api('assets', form);
  await api('evaluate', { versionIds: [version.id] });
  await api('publish', { versionId: version.id, sellerAmount: String(price), platformFee: '10', maxDiscount: '5', validDays: 30 });
  return version;
}
