async function client(role) {
  const login = await fetch(`${origin}/api/market/login`, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ role }) });
  const cookie = login.headers.get('set-cookie')?.split(';')[0];
  if (!login.ok || !cookie) throw new Error('Local login failed');
  return async (route, body) => {
    const response = await fetch(`${origin}/api/market/${route}`, body === undefined ? { headers: { Cookie: cookie } } : { method: 'POST', headers: { Origin: origin, Cookie: cookie, ...(body instanceof FormData ? {} : { 'Content-Type': 'application/json' }) }, body: body instanceof FormData ? body : JSON.stringify(body) });
    const result = await response.json();
    if (!response.ok) throw new Error(result.error);
    return result;
  };
}
